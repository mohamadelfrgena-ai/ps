-- -------------------------------------------------------------------
-- 17) غرفة «خدمات النقدية» — للقراءة فقط (يكتب فيها الأدمن وحده)
-- -------------------------------------------------------------------
-- التطبيق فيه زر «➕ إضافة غرفة» في (الأدمن ← الشات) ينشئ الغرفة نفسها،
-- فهذا السكربت اختياري لمن يفضّل إنشاءها من قاعدة البيانات مباشرة.
--
-- ملاحظة مهمة: المنع **مفروض في الخادم أصلاً** — دالة الإرسال تفحص
--   is_locked و post_permission قبل قبول أي رسالة، فلا يمكن لأي مستخدم
--   إرسال رسالة في هذه الغرفة حتى لو حاول عبر واجهة برمجية أخرى.
--   عملياً: البَثّ يتم من «إعلان» في الأدمن ← الشات، أو من حساب الأدمن نفسه.
--
-- لا يغيّر أي جدول أو دالة — إدراج صف واحد فقط (idempotent).

insert into public.chat_channels (
  id, name, icon, category, description, sort_order, is_locked, slowmode_seconds, post_permission
)
values (
  'cash-services',            -- المعرّف: لاتيني، ثابت، لا يتغير
  'خدمات النقدية',            -- الاسم الظاهر
  '💵',                       -- الأيقونة
  'main',                     -- قسم الغرف الرئيسية
  'مقالات وخدمات نقدية — القراءة للجميع، والكتابة للإدارة فقط.',
  2,                          -- الترتيب: بعد الغرفة الرئيسية
  true,                       -- مقفلة ⇐ لا يكتب إلا الأدمن/المشرف
  0,                          -- بلا بطء إرسال
  'admin_only'                -- صلاحية النشر: الأدمن وحده
)
on conflict (id) do update
   set name = excluded.name,
       icon = excluded.icon,
       description = excluded.description,
       is_locked = true,
       post_permission = 'admin_only';

-- تحقّق: يجب أن يخرج صف واحد
select id, name, is_locked, post_permission
  from public.chat_channels
 where id = 'cash-services';
