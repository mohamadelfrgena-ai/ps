#!/usr/bin/env python3
"""Generate audio_bank.cpp from assets/sfx/*.wav (v0.29).

The HUD sounds ship as C arrays inside the eboot so they can never go missing
at runtime (no /app0 path, no PKG entry, no fopen). Each clip is transcoded to
the exact mixer format (PCM16 / mono / 48 kHz — the loader rejects anything
else) and normalized to ~88% full scale so every cue is clearly audible.

Usage:
    python3 tools/gen_audio_bank.py <out.cpp> [assets/sfx]
"""
import os
import struct
import sys


def read_wav(path):
    with open(path, "rb") as f:
        data = f.read()
    if data[:4] != b"RIFF" or data[8:12] != b"WAVE":
        raise SystemExit("not a RIFF/WAVE file: " + path)
    pos = 12
    fmt = None
    pcm = None
    while pos + 8 <= len(data):
        cid = data[pos:pos + 4]
        sz = struct.unpack("<I", data[pos + 4:pos + 8])[0]
        pos += 8
        chunk = data[pos:pos + sz]
        if cid == b"fmt ":
            fmt = struct.unpack("<HHIIHH", chunk[:16])
        elif cid == b"data":
            pcm = chunk
        pos += sz + (sz & 1)
    if fmt is None or pcm is None:
        raise SystemExit("missing fmt/data chunk: " + path)
    audio_fmt, ch, rate, _, _, bits = fmt
    if audio_fmt != 1 or bits != 16 or rate != 48000 or ch != 1:
        raise SystemExit("unexpected wav format %s (need PCM16 mono 48kHz): %s"
                         % (str(fmt), path))
    return pcm


def normalize(pcm):
    ns = len(pcm) // 2
    if ns == 0:
        return pcm
    s = struct.unpack("<%dh" % ns, pcm[:ns * 2])
    peak = max(abs(x) for x in s)
    if peak <= 0:
        return pcm
    target = 29000
    if peak < target:
        s = [int(x * target / peak) for x in s]
        pcm = struct.pack("<%dh" % ns, *s)
    return pcm


def build(out_path, src_dir):
    names = sorted(n for n in os.listdir(src_dir) if n.endswith(".wav"))
    if not names:
        raise SystemExit("no .wav files in " + src_dir)
    lines = [
        "// audio_bank.cpp — GENERATED by tools/gen_audio_bank.py — do not edit.",
        '#include "audio_bank.hpp"',
        "",
        "namespace pkgtest {",
        "namespace {",
    ]
    for i, n in enumerate(names):
        pcm = normalize(read_wav(os.path.join(src_dir, n)))
        lines.append("const unsigned char kWav%d[] = {" % i)
        row = "  "
        for b in pcm:
            row += "0x%02x," % b
            if len(row) >= 96:
                lines.append(row)
                row = "  "
        if row.strip():
            lines.append(row)
        lines.append("};")
    lines.append("} // namespace")
    lines.append("")
    lines.append("const AudioClipBankEntry kAudioBank[] = {")
    for i, n in enumerate(names):
        stem = n[:-4]
        lines.append('    {"%s", kWav%d, sizeof(kWav%d)},' % (stem, i, i))
    lines.append("};")
    lines.append("const int kAudioBankCount = %d;" % len(names))
    lines.append("")
    lines.append("} // namespace pkgtest")
    lines.append("")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote %s with %d clips" % (out_path, len(names)))


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    build(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "assets/sfx")
    return 0


if __name__ == "__main__":
    sys.exit(main())
