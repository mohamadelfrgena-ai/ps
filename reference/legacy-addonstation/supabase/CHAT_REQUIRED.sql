-- Temporary mutes used by the moderation check.
create table if not exists public.chat_mutes (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  reason text,
  expires_at timestamptz not null,
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

alter table public.chat_mutes enable row level security;
grant select, insert, update, delete on public.chat_mutes to authenticated;
drop policy if exists "addon_chat_mutes_manage" on public.chat_mutes;
create policy "addon_chat_mutes_manage"
on public.chat_mutes for all to authenticated
using (public.is_chat_moderator())
with check (public.is_chat_moderator());

-- Replace the temporary insert policy with one that also blocks muted users.
drop policy if exists "addon_chat_messages_insert" on public.chat_messages;
create policy "addon_chat_messages_insert"
on public.chat_messages for insert to authenticated
with check (
  auth.uid() = user_id
  and status = 'published'
  and exists (
    select 1 from public.chat_channels
    where id = channel_id and is_public = true
  )
  and not exists (
    select 1 from public.chat_mutes
    where user_id = auth.uid() and expires_at > now()
  )
);

