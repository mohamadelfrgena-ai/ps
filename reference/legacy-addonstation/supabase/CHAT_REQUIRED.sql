-- Messages
create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  channel_id uuid references public.chat_channels(id) on delete restrict,
  content text not null default '',
  sticker_url text,
  reply_to_id bigint references public.chat_messages(id) on delete set null,
  thread_root_id bigint references public.chat_messages(id) on delete set null,
  status text not null default 'published' check (status in ('published','hidden','flagged')),
  created_at timestamptz not null default now(),
  constraint addon_chat_message_content check (char_length(trim(content)) between 1 and 500 or sticker_url is not null)
);

alter table public.chat_messages add column if not exists channel_id uuid references public.chat_channels(id) on delete restrict;
alter table public.chat_messages add column if not exists reply_to_id bigint references public.chat_messages(id) on delete set null;
alter table public.chat_messages add column if not exists thread_root_id bigint references public.chat_messages(id) on delete set null;
alter table public.chat_messages add column if not exists sticker_url text;
alter table public.chat_messages add column if not exists status text not null default 'published';
alter table public.chat_messages add column if not exists created_at timestamptz not null default now();

