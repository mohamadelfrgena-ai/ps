-- AddonStation dynamic content catalogue

create table if not exists public.content_items (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  content_type text not null check (content_type in ('addon', 'world')),
  title text not null check (char_length(title) between 2 and 120),
  description text not null default '',
  category text not null default 'general',
  version text not null default '1.0.0',
  cover_url text,
  file_path text,
  plan text not null default 'free' check (plan in ('free', 'epic', 'legendary')),
  is_published boolean not null default true,
  is_featured boolean not null default false,
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  view_count integer not null default 0,
  download_count integer not null default 0,
  rating_average numeric(3,2) not null default 0,
  rating_count integer not null default 0
);

create table if not exists public.content_favorites (
  user_id uuid not null references public.profiles(id) on delete cascade,
  content_id uuid not null references public.content_items(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, content_id)
);

create table if not exists public.content_downloads (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  content_id uuid not null references public.content_items(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (user_id, content_id)
);

create table if not exists public.content_reviews (
  user_id uuid not null references public.profiles(id) on delete cascade,
  content_id uuid not null references public.content_items(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  review_text text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, content_id)
);

create index if not exists content_items_type_created_idx on public.content_items(content_type, created_at desc);
create index if not exists content_items_type_views_idx on public.content_items(content_type, view_count desc);
create index if not exists content_items_type_downloads_idx on public.content_items(content_type, download_count desc);

alter table public.content_items add column if not exists category text not null default 'general';
alter table public.content_items add column if not exists version text not null default '1.0.0';

create index if not exists content_items_category_idx on public.content_items(category);

alter table public.content_items enable row level security;
alter table public.content_favorites enable row level security;
alter table public.content_downloads enable row level security;
alter table public.content_reviews enable row level security;

-- Public catalogue; unpublished content stays private to managers.
create policy "Public can view published content"
on public.content_items for select to anon, authenticated
using (is_published = true or public.is_chat_moderator());

create policy "Managers can manage content"
on public.content_items for all to authenticated
using (public.is_chat_moderator())
with check (public.is_chat_moderator());

-- PostgREST needs table privileges in addition to RLS policies.
grant select on public.content_items to anon, authenticated;
grant insert, update, delete on public.content_items to authenticated;

create policy "Users manage own favorites"
on public.content_favorites for all to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy "Users view own downloads"
on public.content_downloads for select to authenticated
using (auth.uid() = user_id);

create policy "Users add own downloads"
on public.content_downloads for insert to authenticated
with check (auth.uid() = user_id);

create policy "Public can view reviews"
on public.content_reviews for select to anon, authenticated
using (true);

create policy "Users manage own reviews"
on public.content_reviews for all to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

-- Browser clients on the website and mobile app use the same catalog tables.
grant select, insert, update, delete on public.content_favorites to authenticated;
grant select on public.content_reviews to anon, authenticated;
grant insert, update, delete on public.content_reviews to authenticated;
grant select, insert on public.content_downloads to authenticated;

create or replace function public.refresh_content_rating()
returns trigger language plpgsql security definer set search_path = public as $$
declare target_id uuid;
begin
  target_id := coalesce(new.content_id, old.content_id);
  update public.content_items
  set rating_average = coalesce((select round(avg(rating)::numeric, 2) from public.content_reviews where content_id = target_id), 0),
      rating_count = (select count(*) from public.content_reviews where content_id = target_id),
      updated_at = now()
  where id = target_id;
  return coalesce(new, old);
end;
$$;

drop trigger if exists content_review_rating on public.content_reviews;
create trigger content_review_rating
after insert or update or delete on public.content_reviews
for each row execute procedure public.refresh_content_rating();

create or replace function public.record_content_view(item_id uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  update public.content_items set view_count = view_count + 1 where id = item_id and is_published = true;
end;
$$;

create or replace function public.record_content_download(item_id uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'Login required'; end if;
  insert into public.content_downloads(user_id, content_id) values(auth.uid(), item_id) on conflict do nothing;
  if found then update public.content_items set download_count = download_count + 1 where id = item_id; end if;
end;
$$;

grant execute on function public.record_content_view(uuid) to anon, authenticated;
grant execute on function public.record_content_download(uuid) to authenticated;

