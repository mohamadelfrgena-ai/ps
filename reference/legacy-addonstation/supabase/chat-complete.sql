-- AddonStation Chat - complete one-time setup
-- شغّل هذا الملف مرة واحدة فقط من Supabase SQL Editor.
-- أوقف الموقع والتطبيق، وأغلق أي تبويب SQL آخر لتجنب deadlock.
-- لا يحتاج إلى Service Role Key.

begin;

create extension if not exists pgcrypto;

-- 1) القنوات
create table if not exists public.chat_channels (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name text not null,
  description text not null default '',
  position integer not null default 0,
  is_public boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.chat_channels (slug, name, description, position)
values
  ('general', 'general', 'General community discussion', 1),
  ('minecraft', 'minecraft', 'Minecraft gameplay and ideas', 2),
  ('addons', 'addons', 'Add-ons and installation discussion', 3),
  ('ps4', 'ps4', 'PS4 community and connection help', 4),
  ('creators', 'creators', 'Creator content and publishing', 5),
  ('support', 'support', 'Help and support questions', 6)
on conflict (slug) do nothing;

-- 2) الرسائل
create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  channel_id uuid references public.chat_channels(id) on delete restrict,
  content text not null default '',
  sticker_url text,
  reply_to_id bigint references public.chat_messages(id) on delete set null,
  thread_root_id bigint references public.chat_messages(id) on delete set null,
  status text not null default 'published',
  created_at timestamptz not null default now()
);

alter table public.chat_messages add column if not exists channel_id uuid references public.chat_channels(id) on delete restrict;
alter table public.chat_messages add column if not exists content text not null default '';
alter table public.chat_messages add column if not exists sticker_url text;
alter table public.chat_messages add column if not exists reply_to_id bigint references public.chat_messages(id) on delete set null;
alter table public.chat_messages add column if not exists thread_root_id bigint references public.chat_messages(id) on delete set null;
alter table public.chat_messages add column if not exists status text not null default 'published';
alter table public.chat_messages add column if not exists created_at timestamptz not null default now();

create or replace function public.default_general_channel()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select id from public.chat_channels where slug = 'general' limit 1;
$$;

update public.chat_messages
set channel_id = public.default_general_channel()
where channel_id is null;

alter table public.chat_messages
  alter column channel_id set default public.default_general_channel();
alter table public.chat_messages
  alter column channel_id set not null;

create index if not exists chat_messages_channel_created_idx
  on public.chat_messages(channel_id, created_at asc, id asc);
create index if not exists chat_messages_thread_idx
  on public.chat_messages(thread_root_id, created_at asc);

-- 3) ميزات الشات الإضافية
create table if not exists public.chat_rule_acceptances (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  accepted_at timestamptz not null default now()
);

create table if not exists public.chat_reactions (
  message_id bigint not null references public.chat_messages(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  emoji text not null check (char_length(emoji) between 1 and 32),
  created_at timestamptz not null default now(),
  primary key (message_id, user_id, emoji)
);

create table if not exists public.chat_images (
  id uuid primary key default gen_random_uuid(),
  message_id bigint not null references public.chat_messages(id) on delete cascade,
  uploader_id uuid not null references public.profiles(id) on delete cascade,
  image_path text not null,
  mime_type text not null check (mime_type in ('image/jpeg', 'image/png', 'image/webp')),
  image_size integer not null check (image_size > 0 and image_size <= 4194304),
  created_at timestamptz not null default now()
);

create table if not exists public.chat_mutes (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  reason text,
  expires_at timestamptz not null,
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.chat_notifications (
  id uuid primary key default gen_random_uuid(),
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  actor_id uuid references public.profiles(id) on delete set null,
  notification_type text not null,
  message_id bigint references public.chat_messages(id) on delete cascade,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.user_friends (
  requester_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (requester_id, receiver_id),
  check (requester_id <> receiver_id)
);

create index if not exists chat_notifications_recipient_idx
  on public.chat_notifications(recipient_id, is_read, created_at desc);

-- 4) الصلاحيات و RLS
create or replace function public.is_chat_moderator()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid()
      and (role in ('admin', 'moderator') or is_admin = true)
  );
$$;

grant select on public.profiles to authenticated;
grant select on public.chat_channels to authenticated;
grant select, insert, update, delete on public.chat_messages to authenticated;
grant select, insert, update on public.chat_rule_acceptances to authenticated;
grant select, insert, update, delete on public.chat_reactions to authenticated;
grant select, insert, delete on public.chat_images to authenticated;
grant select, insert, update, delete on public.chat_mutes to authenticated;
grant select, insert, update on public.chat_notifications to authenticated;
grant select, insert, update, delete on public.user_friends to authenticated;

do $$
declare
  sequence_name text;
begin
  select pg_get_serial_sequence('public.chat_messages', 'id') into sequence_name;
  if sequence_name is not null then
    execute format('grant usage, select on sequence %s to authenticated', sequence_name);
  end if;
end $$;

alter table public.chat_channels enable row level security;
alter table public.chat_messages enable row level security;
alter table public.chat_rule_acceptances enable row level security;
alter table public.chat_reactions enable row level security;
alter table public.chat_images enable row level security;
alter table public.chat_mutes enable row level security;
alter table public.chat_notifications enable row level security;
alter table public.user_friends enable row level security;

drop policy if exists chat_complete_channels_read on public.chat_channels;
create policy chat_complete_channels_read on public.chat_channels
for select to authenticated using (is_public = true or public.is_chat_moderator());

drop policy if exists chat_complete_messages_read on public.chat_messages;
create policy chat_complete_messages_read on public.chat_messages
for select to authenticated using (status = 'published');

drop policy if exists chat_complete_messages_insert on public.chat_messages;
create policy chat_complete_messages_insert on public.chat_messages
for insert to authenticated
with check (
  auth.uid() = user_id
  and status = 'published'
  and exists (select 1 from public.chat_channels c where c.id = channel_id and c.is_public = true)
  and not exists (select 1 from public.chat_mutes m where m.user_id = auth.uid() and m.expires_at > now())
);

drop policy if exists chat_complete_messages_delete on public.chat_messages;
create policy chat_complete_messages_delete on public.chat_messages
for delete to authenticated using (auth.uid() = user_id or public.is_chat_moderator());

drop policy if exists chat_complete_rules_read on public.chat_rule_acceptances;
create policy chat_complete_rules_read on public.chat_rule_acceptances
for select to authenticated using (user_id = auth.uid());
drop policy if exists chat_complete_rules_write on public.chat_rule_acceptances;
create policy chat_complete_rules_write on public.chat_rule_acceptances
for insert to authenticated with check (user_id = auth.uid());

drop policy if exists chat_complete_reactions_read on public.chat_reactions;
create policy chat_complete_reactions_read on public.chat_reactions
for select to authenticated using (true);
drop policy if exists chat_complete_reactions_write on public.chat_reactions;
create policy chat_complete_reactions_write on public.chat_reactions
for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists chat_complete_images_read on public.chat_images;
create policy chat_complete_images_read on public.chat_images
for select to authenticated using (true);
drop policy if exists chat_complete_images_write on public.chat_images;
create policy chat_complete_images_write on public.chat_images
for insert to authenticated with check (uploader_id = auth.uid());
drop policy if exists chat_complete_images_delete on public.chat_images;
create policy chat_complete_images_delete on public.chat_images
for delete to authenticated using (uploader_id = auth.uid() or public.is_chat_moderator());

drop policy if exists chat_complete_mutes_manage on public.chat_mutes;
create policy chat_complete_mutes_manage on public.chat_mutes
for all to authenticated using (public.is_chat_moderator()) with check (public.is_chat_moderator());

drop policy if exists chat_complete_notifications_read on public.chat_notifications;
create policy chat_complete_notifications_read on public.chat_notifications
for select to authenticated using (recipient_id = auth.uid());
drop policy if exists chat_complete_notifications_update on public.chat_notifications;
create policy chat_complete_notifications_update on public.chat_notifications
for update to authenticated using (recipient_id = auth.uid()) with check (recipient_id = auth.uid());
drop policy if exists chat_complete_notifications_insert on public.chat_notifications;
create policy chat_complete_notifications_insert on public.chat_notifications
for insert to authenticated with check (actor_id = auth.uid());

drop policy if exists chat_complete_friends_read on public.user_friends;
create policy chat_complete_friends_read on public.user_friends
for select to authenticated using (requester_id = auth.uid() or receiver_id = auth.uid());
drop policy if exists chat_complete_friends_insert on public.user_friends;
create policy chat_complete_friends_insert on public.user_friends
for insert to authenticated with check (requester_id = auth.uid());
drop policy if exists chat_complete_friends_update on public.user_friends;
create policy chat_complete_friends_update on public.user_friends
for update to authenticated using (requester_id = auth.uid() or receiver_id = auth.uid()) with check (requester_id = auth.uid() or receiver_id = auth.uid());

-- 5) دالة إرسال سريعة وآمنة
create or replace function public.send_chat_message(
  p_channel_id uuid,
  p_content text default '',
  p_sticker_url text default null,
  p_reply_to_id bigint default null,
  p_thread_root_id bigint default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_message_id bigint;
  clean_content text := trim(coalesce(p_content, ''));
  is_muted boolean := false;
begin
  if auth.uid() is null then
    raise exception 'Login required.';
  end if;

  if not exists (select 1 from public.chat_channels where id = p_channel_id and is_public = true) then
    raise exception 'This chat channel is not available.';
  end if;

  if clean_content = '' and p_sticker_url is null then
    raise exception 'Message cannot be empty.';
  end if;
  if char_length(clean_content) > 500 then
    raise exception 'Message is too long.';
  end if;

  if to_regclass('public.chat_mutes') is not null then
    execute 'select exists (select 1 from public.chat_mutes where user_id = $1 and expires_at > now())'
      into is_muted using auth.uid();
  end if;
  if is_muted then
    raise exception 'You are temporarily muted.';
  end if;

  insert into public.chat_messages
    (user_id, channel_id, content, sticker_url, reply_to_id, thread_root_id, status)
  values
    (auth.uid(), p_channel_id, clean_content, p_sticker_url, p_reply_to_id, p_thread_root_id, 'published')
  returning id into new_message_id;

  return new_message_id;
end;
$$;

revoke all on function public.send_chat_message(uuid, text, text, bigint, bigint) from public;
grant execute on function public.send_chat_message(uuid, text, text, bigint, bigint) to authenticated;

-- 6) صور الشات
insert into storage.buckets (id, name, public, file_size_limit)
values ('chat-images', 'chat-images', false, 4194304)
on conflict (id) do nothing;

drop policy if exists chat_complete_storage_insert on storage.objects;
create policy chat_complete_storage_insert on storage.objects
for insert to authenticated
with check (bucket_id = 'chat-images' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists chat_complete_storage_read on storage.objects;
create policy chat_complete_storage_read on storage.objects
for select to authenticated
using (bucket_id = 'chat-images');

drop policy if exists chat_complete_storage_delete on storage.objects;
create policy chat_complete_storage_delete on storage.objects
for delete to authenticated
using (bucket_id = 'chat-images' and ((storage.foldername(name))[1] = auth.uid()::text or public.is_chat_moderator()));

-- 7) Realtime (إذا كانت publication موجودة)
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (
      select 1 from pg_publication_rel pr
      join pg_publication p on p.oid = pr.prpubid
      join pg_class c on c.oid = pr.prrelid
      join pg_namespace n on n.oid = c.relnamespace
      where p.pubname = 'supabase_realtime' and n.nspname = 'public' and c.relname = 'chat_messages'
    ) then
      alter publication supabase_realtime add table public.chat_messages;
    end if;
    if not exists (
      select 1 from pg_publication_rel pr
      join pg_publication p on p.oid = pr.prpubid
      join pg_class c on c.oid = pr.prrelid
      join pg_namespace n on n.oid = c.relnamespace
      where p.pubname = 'supabase_realtime' and n.nspname = 'public' and c.relname = 'chat_reactions'
    ) then
      alter publication supabase_realtime add table public.chat_reactions;
    end if;
  end if;
end $$;

commit;
